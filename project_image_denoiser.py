def draw_map(points_2d, point_labels, title):
    plt.figure(figsize=(8, 7))
    dots = plt.scatter(points_2d[:, 0], points_2d[:, 1],
                       c=point_labels, cmap="tab10", s=3, alpha=0.6)
    for digit in range(10):
        centre = np.median(points_2d[point_labels == digit], axis=0)
        plt.text(centre[0], centre[1], str(digit), fontsize=16,
                 ha="center", va="center",
                 bbox=dict(boxstyle="circle", facecolor="white", alpha=0.85))
    plt.colorbar(dots, ticks=range(10), label="digit (the label we IGNORED)")
    plt.title(title)
    plt.show()


