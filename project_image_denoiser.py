import torch
import torch.nn as nn
import matplotlib.pyplot as plt
from torchvision import datasets, transforms
from torch.utils.data import DataLoader

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Using device:", device)

# Download MNIST and turn each image into numbers between 0 and 1
to_numbers = transforms.ToTensor()

train_data = datasets.MNIST(root="./data", train=True,  download=True, transform=to_numbers)
test_data  = datasets.MNIST(root="./data", train=False, download=True, transform=to_numbers)

print("\ntraining pictures:", len(train_data))
print("test pictures:    ", len(test_data))

one_picture, one_label = train_data[0]
